/**
 * Version single source of truth: `plugin.meta.json`.
 *
 * `node scripts/version.ts` (default) checks every copy; `--write` rewrites them.
 * Copies: the three package.json files, the generated `core/src/version.ts`, and
 * the three doc spots that quote the released version. CHANGELOG headings are
 * history and are deliberately never rewritten.
 *
 * Run from `server/` or by path; paths resolve against this file, not the cwd.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PLUGIN_ROOT = fileURLToPath(new URL('../..', import.meta.url));

interface Target {
  /** Path relative to the plugin root. */
  readonly file: string;
  readonly pattern: RegExp;
  /** 1-based capture group carrying the version. Ignored when `render` is set. */
  readonly group: number;
  readonly why: string;
  /** Regenerates the whole file instead of patching one capture group. */
  readonly render?: (version: string) => string;
}

const TARGETS: readonly Target[] = [
  {
    file: 'core/src/version.ts',
    pattern: /export const VERSION = '([0-9]+\.[0-9]+\.[0-9]+)'/,
    group: 1,
    why: 'core VERSION 常量（生成文件）',
    render: (version) =>
      '/** Generated by server/scripts/version.ts from plugin.meta.json; do not edit by hand. @module */\n' +
      `\nexport const VERSION = '${version}';\n`,
  },
  ...(['core', 'server', 'web'] as const).map((pkg) => ({
    file: `${pkg}/package.json`,
    pattern: /^(\s*"version": ")([0-9]+\.[0-9]+\.[0-9]+)"/m,
    group: 2,
    why: `${pkg}/package.json`,
  })),
  {
    file: 'docs/protocol.md',
    pattern: /("name": "repl-server", "version": ")([0-9]+\.[0-9]+\.[0-9]+)(")/,
    group: 2,
    why: 'protocol.md 的 serverInfo 示例',
  },
  {
    file: 'INSTALL.md',
    pattern: /("version":")([0-9]+\.[0-9]+\.[0-9]+)(")/,
    group: 2,
    why: 'INSTALL.md 的 /health 预期输出',
  },
  {
    file: 'README.md',
    pattern: /(\*\*)([0-9]+\.[0-9]+\.[0-9]+)(\*\*：MCP 端点)/,
    group: 2,
    why: 'README.md 的版本行',
  },
];

interface Finding {
  readonly target: Target;
  readonly actual: string | undefined;
  readonly ok: boolean;
}

async function readVersion(): Promise<string> {
  const text = await readFile(join(PLUGIN_ROOT, 'plugin.meta.json'), 'utf8');
  const version = (JSON.parse(text) as { version?: unknown }).version;
  if (typeof version !== 'string' || !/^[0-9]+\.[0-9]+\.[0-9]+$/.test(version)) {
    throw new Error('plugin.meta.json 的 version 必须是 x.y.z');
  }
  return version;
}

async function inspect(target: Target, version: string): Promise<Finding> {
  const path = join(PLUGIN_ROOT, target.file);
  const text = await readFile(path, 'utf8');
  if (target.render !== undefined) {
    return { target, actual: text === target.render(version) ? version : '(内容不同)', ok: text === target.render(version) };
  }
  const match = target.pattern.exec(text);
  const actual = match?.[target.group];
  return { target, actual, ok: actual === version };
}

async function writeAll(version: string): Promise<void> {
  for (const target of TARGETS) {
    const path = join(PLUGIN_ROOT, target.file);
    const text = await readFile(path, 'utf8');
    if (target.render !== undefined) {
      await writeFile(path, target.render(version));
      continue;
    }
    const match = target.pattern.exec(text);
    if (match === null) throw new Error(`${target.file}: 未命中 ${target.pattern}，无法写入`);
    const captured = match[target.group] ?? '';
    if (captured === version) continue;
    const replaced = text.replace(target.pattern, (whole: string) => whole.replace(captured, version));
    if (replaced === text) throw new Error(`${target.file}: 替换未生效（${captured}）`);
    await writeFile(path, replaced);
  }
}

async function main(): Promise<number> {
  const write = process.argv.includes('--write');
  const version = await readVersion();

  if (write) {
    await writeAll(version);
    console.log(`已把版本 ${version} 写入 ${TARGETS.length} 处`);
    return 0;
  }

  const findings = await Promise.all(TARGETS.map((target) => inspect(target, version)));
  const broken = findings.filter((finding) => !finding.ok);
  for (const finding of broken) {
    const where = `${finding.target.file}`;
    const seen = finding.actual ?? '未命中';
    console.error(`error: ${where} 是 ${seen}，应为 ${version}（${finding.target.why}）`);
  }
  if (broken.length > 0) {
    console.error(`版本校验失败：${broken.length}/${TARGETS.length} 处不一致。用 --write 同步。`);
    return 1;
  }
  console.log(`版本校验通过：${version}（${TARGETS.length} 处一致）`);
  return 0;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main();
}
